-- Portfolio schema. Run in an empty Supabase project after reviewing the target schema.
-- This creates exactly the nine application tables; Storage remains Supabase-managed.
begin;

create table if not exists public.portfolio_profile (
  singleton_id smallint primary key default 1 check (singleton_id = 1),
  name text not null,
  titles text[] not null default '{}',
  description text not null,
  about_title text not null,
  about_text text not null,
  about_education text not null,
  about_projects text not null,
  import_fingerprint text check (import_fingerprint is null or import_fingerprint ~ '^[0-9a-f]{64}$'),
  updated_at timestamptz not null default now()
);

create table if not exists public.portfolio_skills (
  id uuid primary key,
  category text not null check (category in ('frontend', 'backend')),
  sort_order integer not null check (sort_order >= 0),
  name text not null,
  percentage smallint not null check (percentage between 0 and 100),
  icon text not null,
  updated_at timestamptz not null default now(),
  unique (category, sort_order)
);

create table if not exists public.portfolio_education (
  id uuid primary key,
  sort_order integer not null unique check (sort_order >= 0),
  date_label text not null,
  title text not null,
  subtitle text not null,
  description text not null,
  bullets text[] not null default '{}',
  tags text[] not null default '{}',
  icon text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.portfolio_experience (
  id uuid primary key,
  sort_order integer not null unique check (sort_order >= 0),
  date_label text not null,
  title text not null,
  role_type text not null,
  type_class text not null check (type_class ~ '^exp-timeline__type--[a-z-]+$'),
  company text not null,
  bullets text[] not null default '{}',
  tags text[] not null default '{}',
  icon text not null,
  theme_color text not null check (
    theme_color ~* '^(var\(--[a-z0-9-]+\)|#[0-9a-f]{3,8}|rgba?\([0-9,. %]+\))$'
  ),
  theme_color_rgb text not null check (
    theme_color_rgb ~ '^[0-9]{1,3},[[:space:]]*[0-9]{1,3},[[:space:]]*[0-9]{1,3}$'
  ),
  updated_at timestamptz not null default now()
);

create table if not exists public.portfolio_projects (
  id uuid primary key,
  sort_order integer not null unique check (sort_order >= 0),
  name text not null,
  category text not null default 'Web App',
  language text not null default '',
  description text not null default '',
  html_url text not null check (html_url ~* '^https://[^/@]+(/|$)'),
  homepage text not null default '',
  image text not null default '',
  video text not null default '',
  stargazers_count integer not null default 0 check (stargazers_count >= 0),
  forks_count integer not null default 0 check (forks_count >= 0),
  updated_at timestamptz not null default now(),
  check (homepage = '' or homepage ~* '^https://[^/@]+(/|$)' or homepage ~ '^/assets/[A-Za-z0-9_./-]+$'),
  check (image = '' or image ~* '^https://[^/@]+(/|$)' or image ~ '^/assets/[A-Za-z0-9_./-]+$'),
  check (video = '' or video ~* '^https://[^/@]+(/|$)' or video ~ '^/assets/[A-Za-z0-9_./-]+$'),
  check (homepage !~ '(^|/)\.\.(/|$)' and image !~ '(^|/)\.\.(/|$)' and video !~ '(^|/)\.\.(/|$)')
);

create table if not exists public.portfolio_certificates (
  id uuid primary key,
  sort_order integer not null unique check (sort_order >= 0),
  name text not null,
  issuer text not null,
  date_label text not null,
  credential_url text not null default '',
  image text not null default '',
  pdf text not null default '',
  updated_at timestamptz not null default now(),
  check (credential_url = '' or credential_url ~* '^https://[^/@]+(/|$)' or credential_url ~ '^/assets/[A-Za-z0-9_./-]+$'),
  check (image = '' or image ~* '^https://[^/@]+(/|$)' or image ~ '^/assets/[A-Za-z0-9_./-]+$'),
  check (pdf = '' or pdf ~* '^https://[^/@]+(/|$)' or pdf ~ '^/assets/[A-Za-z0-9_./-]+$'),
  check (credential_url !~ '(^|/)\.\.(/|$)' and image !~ '(^|/)\.\.(/|$)' and pdf !~ '(^|/)\.\.(/|$)')
);

create table if not exists public.contact_messages (
  id text primary key check (length(id) between 1 and 64),
  sort_order bigint generated by default as identity unique,
  name text not null,
  email text not null,
  message text not null,
  date_label text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_sessions (
  token_hash text primary key check (token_hash ~ '^[0-9a-f]{64}$'),
  csrf_token_hash text not null check (csrf_token_hash ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  revoked_at timestamptz,
  check (expires_at > created_at)
);

create table if not exists public.rate_limit_buckets (
  scope text not null check (scope in ('login', 'contact', 'upload')),
  subject_hash text not null check (subject_hash ~ '^[0-9a-f]{64}$'),
  request_count integer not null check (request_count > 0),
  reset_at timestamptz not null,
  primary key (scope, subject_hash)
);

create index if not exists contact_messages_order_idx
  on public.contact_messages (sort_order desc);
create index if not exists admin_sessions_expiry_idx
  on public.admin_sessions (expires_at)
  where revoked_at is null;
create index if not exists rate_limit_buckets_reset_idx
  on public.rate_limit_buckets (reset_at);

commit;
